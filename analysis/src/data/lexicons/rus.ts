// Russian. `\b` in JS regexes only knows ASCII letters, so it never fires next
// to Cyrillic — every phrase here is wrapped in Unicode-aware letter/digit
// lookarounds instead. Phrase-grade only, precision over recall (see README):
// single common words ("заказ") never match alone in confirmation-grade lists.
const w = (source: string): RegExp =>
  new RegExp(`(?<![\\p{L}\\d])(?:${source})(?![\\p{L}\\d])`, "iu");

